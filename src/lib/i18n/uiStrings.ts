export function getUiStrings(lang: LanguageCode): UiStrings {
  return UI_STRINGS[lang] ?? UI_STRINGS.en;
}

/** Plain-text wordmark (no accent-color split) — used in `<title>`, not on-page. */
export function getBrandName(lang: LanguageCode): string {
  const { before, accent, after } = getUiStrings(lang).brand;
  return `${before}${accent}${after}`;
}
