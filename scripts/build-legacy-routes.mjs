// Regenerates src/lib/legacyRoutes.data.ts from public/data/atlas-bootstrap.json.
// Run after any atlas data rebuild: `node scripts/build-legacy-routes.mjs`
// (tests/legacy-routes.test.mjs fails if the generated table drifts from the data).
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const bootstrap = JSON.parse(fs.readFileSync(path.join(root, "public/data/atlas-bootstrap.json"), "utf8"));

/** Same slug rule the retired minimap used for /v2/<lang>/<country-name>/<city>/ URLs. */
export const slugifyName = (s) =>
  s
    .normalize("NFD")
    .replace(/[̀-ͯ]/g, "")
    .toLowerCase()
    .replace(/&/g, "and")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");

const codes = bootstrap.countries.map((c) => c.code.toLowerCase()).sort();
const names = Object.fromEntries(
  bootstrap.countries.map((c) => [slugifyName(c.nameEn), c.code.toLowerCase()]).sort(([a], [b]) => a.localeCompare(b)),
);
const cities = bootstrap.cities.map((c) => c.slug).sort();

const out = `// GENERATED by scripts/build-legacy-routes.mjs from public/data/atlas-bootstrap.json - do not edit.
// Live country codes / city slugs, so the proxy can answer legacy and broken URLs without the 770 KB dataset.

export const COUNTRY_CODES = ${JSON.stringify(codes.join(" "))};

export const CITY_SLUGS = ${JSON.stringify(cities.join(" "))};

/** English country name slug (old minimap URLs) -> live country code. */
export const COUNTRY_NAME_SLUGS: Record<string, string> = ${JSON.stringify(names, null, 2)};
`;
fs.writeFileSync(path.join(root, "src/lib/legacyRoutes.data.ts"), out);
console.log(`legacy routes: ${codes.length} countries, ${cities.length} cities`);
